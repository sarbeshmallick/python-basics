# Marks are given out of 100. Assign a grade based on the marks:

# 80–100 → A
# 60–80 → B
# < 60 → C

# Write a Python program using if, elif, and else to determine and print the grade.





marks = int(input("Enter marks: "))

if marks >= 80:
    print('A')

elif marks >= 60:
    print('B')

else:
    print('C')


