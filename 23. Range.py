
# Range in Python
# range() function returns a range object that is a sequence of numbers. starts from 0 

# numbers = range(5)
# print(numbers)

num = range(5)                            # ( 0, 1, 2, 3, 4)
print(num)



# if we want to start from 1        
num = range(1 , 6)                        # ( 1, 2, 3 , 4, 5)
print(num)



